COMMENT ON COLUMN user_accesses.id IS 'Primary unique identifier';
COMMENT ON COLUMN user_accesses.created_at IS 'Record creation timestamp';
COMMENT ON COLUMN user_accesses.updated_at IS 'Record last update timestamp';
COMMENT ON COLUMN user_accesses.user_uuid IS 'Uuid of the user';
COMMENT ON COLUMN user_accesses.access_treker_create IS 'Permission to create tracker records';
COMMENT ON COLUMN user_accesses.access_treker_edit IS 'Permission to edit tracker records';
COMMENT ON COLUMN user_accesses.access_treker_delete IS 'Permission to delete tracker records';
COMMENT ON COLUMN user_accesses.access_group_manage IS 'Permission to manage device groups';
COMMENT ON COLUMN user_accesses.access_configuration_read IS 'Permission to read device configurations';
COMMENT ON COLUMN user_accesses.access_configuration_apply IS 'Permission to apply device configurations';
COMMENT ON COLUMN user_accesses.access_configuration_history IS 'Permission to view configuration history';
COMMENT ON COLUMN user_accesses.access_command_send IS 'Permission to send commands to devices';
COMMENT ON COLUMN user_accesses.access_log_read IS 'Permission to read system logs';
-- +Comments
