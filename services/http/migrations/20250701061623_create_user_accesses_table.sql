-- +goose Down
-- +goose StatementBegin
DROP TRIGGER IF EXISTS set_updated_at_user_accesses_trigger ON user_accesses;
DROP FUNCTION IF EXISTS set_updated_at_user_accesses();

DROP TABLE IF EXISTS user_accesses;
