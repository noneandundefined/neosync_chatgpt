CREATE OR REPLACE FUNCTION set_updated_at_configurations_prof()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = timezone('UTC', now());
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER set_updated_at_configurations_prof_trigger
    BEFORE UPDATE ON configurations_prof
    FOR EACH ROW
    EXECUTE FUNCTION set_updated_at_configurations_prof();
